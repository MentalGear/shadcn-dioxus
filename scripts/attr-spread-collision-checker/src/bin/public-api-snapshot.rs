#[cfg(test)]
mod tests {
    use super::*;

    fn snap(files: &[(&str, &str)]) -> String {
        use std::sync::atomic::{AtomicUsize, Ordering};
        static N: AtomicUsize = AtomicUsize::new(0);
        let dir = std::env::temp_dir().join(format!(
            "pubapi-test-{}-{}",
            std::process::id(),
            N.fetch_add(1, Ordering::SeqCst)
        ));
        for (name, text) in files {
            let p = dir.join(name);
            fs::create_dir_all(p.parent().expect("parent")).expect("mkdir");
            fs::write(&p, text).expect("write");
        }
        let out = snapshot(&dir).expect("snapshot");
        fs::remove_dir_all(&dir).ok();
        out.lines()
            .filter(|l| !l.starts_with('#'))
            .collect::<Vec<_>>()
            .join("\n")
    }

    fn one(src: &str) -> String {
        snap(&[("lib.rs", src)])
    }

    #[test]
    fn signature_spacing_is_fixed() {
        let out = one("pub fn f<'a, T: Clone + ?Sized>(x: &'a mut Vec<T>, y: Option<(u8, &str)>) -> Result<Box<dyn Fn(u32) -> bool + 'a>, ()> where T: Send {}");
        assert_eq!(out, "f  fn f<'a, T: Clone + ?Sized>(x: &'a mut Vec<T>, y: Option<(u8, &str)>) -> Result<Box<dyn Fn(u32) -> bool + 'a>, ()> where T: Send");
    }

    #[test]
    fn a_trailing_comma_is_not_api() {
        assert_eq!(
            one("pub fn f(a: u8, b: u8,) {}"),
            one("pub fn f(a: u8, b: u8) {}")
        );
        assert_eq!(
            one("pub enum E { A { x: u8, }, }"),
            one("pub enum E { A { x: u8 } }")
        );
    }

    #[test]
    fn only_pub_items_are_listed() {
        let out = one("pub fn a() {}\nfn b() {}\npub(crate) fn c() {}\npub(super) fn d() {}\nmod private { pub fn e() {} }");
        assert_eq!(out, "a  fn a()");
    }

    #[test]
    fn struct_lists_pub_fields_and_marks_private_ones() {
        let out = one("pub struct S<T> { pub a: T, b: u8, /// doc\n pub c: Vec<u8> }\npub struct U(pub u8, u8);\npub struct Unit;");
        assert_eq!(
            out,
            "S  struct S<T>  [private fields]\nS.a  field T\nS.c  field Vec<u8>\nU  struct U  [private fields]\nU.0  field u8\nUnit  struct Unit"
        );
    }

    #[test]
    fn props_attributes_and_derives_are_kept() {
        let out = one("#[derive(Props, Clone, PartialEq)]\npub struct P { #[props(default)] pub id: Option<String>, #[props(extends = GlobalAttributes)] pub attributes: Vec<Attribute> }\n#[component]\npub fn C(props: P) -> Element {}");
        assert_eq!(
            out,
            "C  fn C(props: P) -> Element  #[component]\nP  struct P  #[derive(Props, Clone, PartialEq)]\nP.attributes  field Vec<Attribute>  #[props(extends = GlobalAttributes)]\nP.id  field Option<String>  #[props(default)]"
        );
    }

    #[test]
    fn enums_traits_consts_aliases() {
        let out = one("pub enum E { A, B(u8), C { x: u8 } = 3 }\npub trait T: Clone { fn m(&self) -> u8; fn d(&self) {} type X; }\npub const K: u8 = 5;\npub type Al = Vec<u8>;\npub static S: &str = \"a b\";");
        assert!(out.contains("E  enum E"));
        assert!(out.contains("E::B  variant B(u8)"));
        assert!(out.contains("T  trait T: Clone"));
        assert!(out.contains("T::d  fn d(&self)  [default body]"));
        assert!(out.contains("T::m  fn m(&self) -> u8"));
        assert!(out.contains("T::X  type X"));
        assert!(out.contains("K  const K: u8 = 5"));
        assert!(out.contains("Al  type Al = Vec<u8>"));
        assert!(out.contains("S  static S: &str = \"a b\""));
    }

    #[test]
    fn doc_comments_on_parameters_do_not_leak() {
        let out = one("pub fn f(/// the x\n x: u8) {}");
        assert_eq!(out, "f  fn f(x: u8)");
    }

    #[test]
    fn cfg_is_annotated_and_test_code_dropped() {
        let out = one("#[cfg(feature = \"calendar\")]\npub mod cal { pub fn f() {} }\n#[cfg(test)]\npub fn t() {}\n#[cfg(not(feature = \"web\"))]\npub fn g() {}");
        assert_eq!(
            out,
            "cal  mod  [cfg(feature = \"calendar\")]\ncal::f  fn f()  [cfg(feature = \"calendar\")]\ng  fn g()  [cfg(not(feature = \"web\"))]"
        );
    }

    #[test]
    fn modules_load_from_files_and_inherit_visibility() {
        let out = snap(&[
            ("lib.rs", "pub mod a;\nmod hidden;"),
            ("a.rs", "pub fn f() {}\npub mod nested;"),
            ("a/nested.rs", "pub fn g() {}"),
            ("hidden/mod.rs", "pub fn h() {}"),
        ]);
        assert_eq!(
            out,
            "a  mod\na::f  fn f()\na::nested  mod\na::nested::g  fn g()"
        );
    }

    #[test]
    fn re_exports_list_the_target_under_the_new_path() {
        let out = snap(&[("lib.rs", "mod inner;\npub use inner::{Foo, bar as baz};\npub use inner::*;\npub use other_crate::Thing;"), ("inner.rs", "pub struct Foo { pub x: u8 }\npub fn bar() {}\npub fn glob_fn() {}\nfn private() {}")]);
        assert_eq!(
            out,
            "Foo  struct Foo\nFoo  use inner::Foo\nFoo.x  field u8\nThing  use other_crate::Thing\nbar  fn bar()\nbaz  fn bar()\nbaz  use inner::bar as baz\nglob_fn  fn glob_fn()"
        );
    }

    #[test]
    fn re_export_through_a_module_and_crate_paths() {
        let out = snap(&[(
            "lib.rs",
            "pub mod api { pub use crate::deep::Item; }\nmod deep { pub struct Item; }",
        )]);
        assert_eq!(
            out,
            "api  mod\napi::Item  struct Item\napi::Item  use crate::deep::Item"
        );
    }

    #[test]
    fn impls_attach_to_public_types_only() {
        let out = one("pub struct S;\nstruct P;\nimpl S { pub fn new() -> Self { S } fn hid() {} }\nimpl P { pub fn nope() {} }\nimpl Clone for S { fn clone(&self) -> S { S } }\nimpl Clone for P { fn clone(&self) -> P { P } }");
        assert_eq!(
            out,
            "S  impl Clone for S\nS  struct S\nS::new  fn new() -> Self"
        );
    }

    #[test]
    fn exported_macros_are_listed_at_the_root() {
        let out = snap(&[
            ("lib.rs", "pub mod m;"),
            ("m.rs", "#[macro_export]\nmacro_rules! mk { () => {} }"),
        ]);
        assert!(out.contains("mk  macro mk!"));
    }

    #[test]
    fn output_is_sorted_and_stable() {
        let src = "pub fn z() {}\npub fn a() {}\npub struct M;\nimpl M { pub fn k() {} }";
        assert_eq!(one(src), one(src));
        let lines: Vec<String> = one(src).lines().map(String::from).collect();
        let mut sorted = lines.clone();
        sorted.sort();
        assert_eq!(lines, sorted);
    }

    #[test]
    fn a_private_change_does_not_move_the_snapshot() {
        let a = one("pub fn f(x: u8) -> u8 { x }\nfn p() {}");
        let b = one("pub fn f(x: u8) -> u8 { x + 1 }\nfn p(y: i32) { let _ = y; }\nfn q() {}");
        assert_eq!(a, b);
    }

    #[test]
    fn a_missing_module_file_is_an_error() {
        let dir = std::env::temp_dir().join(format!("pubapi-test-missing-{}", std::process::id()));
        fs::create_dir_all(&dir).expect("mkdir");
        fs::write(dir.join("lib.rs"), "pub mod gone;").expect("write");
        assert!(snapshot(&dir).is_err());
        fs::remove_dir_all(&dir).ok();
    }
}
