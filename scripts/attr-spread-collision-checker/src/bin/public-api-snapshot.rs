//! `public-api-snapshot`: the sorted, stable text snapshot of the public API of a crate's source tree, behind
//! `scripts/check-public-api.sh` (backlog row 266, part c).
//!
//! It walks a crate from its `lib.rs`, following `mod` declarations to their files, and lists every item a user of
//! the crate can name: `pub` functions with their signatures, structs with their `pub` fields and the `#[props(..)]`
//! attributes that make a `#[component]` props field required or optional, enums with their variants, traits with
//! their members, consts, statics, type aliases, `#[macro_export]` macros, `pub mod` declarations, inherent `pub`
//! methods and trait impls of the public types. A `pub use` is followed (crate-local targets, globs included): the
//! target is listed under the re-exported path, and the `use` itself is listed too. An item in a private module is
//! listed only through such a re-export. Items under `#[cfg(test)]` are not API; every other `cfg` is kept as an
//! annotation (`[cfg(feature = "calendar")]`), so the snapshot does not depend on the features of the build that made it.
//!
//! One line per item: `<path>  <kind and signature>  [annotations]`, sorted. The signature text is printed from the
//! token stream with fixed spacing rules (not `rustc` output), so it is stable across runs and formatter versions.
//!
//! Not covered: items generated by macros (a `pub use` of one is reported on stderr and listed as its `use` line only,
//! as `bridge::EventKind`, which a `macro_rules!` defines), `#[path]` modules (an error), and `use` targets outside the
//! crate (the `use` line only).
//!
//! Usage: `public-api-snapshot [--root <src dir>]` (default `primitives/src`); the snapshot goes to stdout.
//! Exit status: 0 on success, 2 on a source file that cannot be read or parsed.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use proc_macro2::{Delimiter, Spacing, TokenStream, TokenTree};
use quote::ToTokens;
use syn::ext::IdentExt;
use syn::{Attribute, ImplItem, Item, Meta, Type, UseTree, Visibility};

// ------------------------------------------------------------------------------------------------ rendering

#[derive(Clone, PartialEq, Debug)]
enum Tok {
    Word(String),
    Op(String),
    Open(char),
    Close(char),
}

fn flatten(ts: TokenStream, out: &mut Vec<Tok>) {
    let mut iter = ts.into_iter().peekable();
    while let Some(tt) = iter.next() {
        match tt {
            TokenTree::Group(g) => {
                let (o, c) = match g.delimiter() {
                    Delimiter::Parenthesis => ('(', ')'),
                    Delimiter::Bracket => ('[', ']'),
                    Delimiter::Brace => ('{', '}'),
                    Delimiter::None => {
                        flatten(g.stream(), out);
                        continue;
                    }
                };
                out.push(Tok::Open(o));
                flatten(g.stream(), out);
                out.push(Tok::Close(c));
            }
            TokenTree::Ident(i) => out.push(Tok::Word(i.to_string())),
            TokenTree::Literal(l) => out.push(Tok::Word(l.to_string())),
            TokenTree::Punct(p) => {
                let mut op = p.as_char().to_string();
                let mut joint = p.spacing() == Spacing::Joint;
                while joint {
                    match iter.peek() {
                        Some(TokenTree::Punct(next)) => {
                            op.push(next.as_char());
                            joint = next.spacing() == Spacing::Joint;
                            iter.next();
                        }
                        _ => break,
                    }
                }
                out.push(Tok::Op(op));
            }
        }
    }
}

fn all_of(op: &str, c: char) -> bool {
    !op.is_empty() && op.chars().all(|x| x == c)
}

/// Whether a space separates two neighbouring tokens.
fn space_between(p: &Tok, n: &Tok) -> bool {
    use Tok::*;
    match (p, n) {
        (Open('{'), Close('}')) => false,
        (Open('{'), _) | (_, Close('}')) | (_, Open('{')) => true,
        (Open(_), _) | (_, Close(_)) => false,
        (Op(o), _)
            if matches!(
                o.as_str(),
                "::" | "&" | "&&" | "*" | "!" | "?" | "'" | "#" | "." | ".." | "..."
            ) || all_of(o, '<') =>
        {
            false
        }
        (_, Op(o))
            if matches!(o.as_str(), "::" | "," | ";" | ":" | "." | "!")
                || all_of(o, '<')
                || all_of(o, '>') =>
        {
            false
        }
        (Word(_), Open('(' | '[')) => false,
        (Op(o), Open('(' | '[')) if all_of(o, '>') || o == "!" || o == "#" => false,
        _ => true,
    }
}

fn render_tokens(ts: TokenStream) -> String {
    let mut raw = Vec::new();
    flatten(ts, &mut raw);
    // a trailing comma before a closer is formatting, not API: rustfmt may add or drop it
    let mut toks: Vec<Tok> = Vec::new();
    for (i, t) in raw.iter().enumerate() {
        let trailing =
            matches!(t, Tok::Op(o) if o == ",") && matches!(raw.get(i + 1), Some(Tok::Close(_)));
        if !trailing {
            toks.push(t.clone());
        }
    }
    let mut s = String::new();
    for (i, t) in toks.iter().enumerate() {
        if i > 0 && space_between(&toks[i - 1], t) {
            s.push(' ');
        }
        match t {
            Tok::Word(w) | Tok::Op(w) => s.push_str(w),
            Tok::Open(c) | Tok::Close(c) => s.push(*c),
        }
    }
    s
}

fn render<T: ToTokens>(t: &T) -> String {
    render_tokens(t.to_token_stream())
}

/// A rendering with the trailing body marker of a header-only clone removed.
fn header(s: String) -> String {
    let s = s.trim_end();
    let s = s.strip_suffix(';').unwrap_or(s).trim_end();
    let s = s
        .strip_suffix("{}")
        .or_else(|| s.strip_suffix("{ }"))
        .unwrap_or(s);
    s.trim_end().to_string()
}

// ------------------------------------------------------------------------------------------------ attributes

const KEEP_ATTRS: &[&str] = &[
    "component",
    "deprecated",
    "must_use",
    "non_exhaustive",
    "derive",
    "repr",
    "props",
    "macro_export",
];

fn attr_name(a: &Attribute) -> String {
    a.path()
        .segments
        .last()
        .map(|s| s.ident.unraw().to_string())
        .unwrap_or_default()
}

fn is_cfg(a: &Attribute) -> bool {
    a.path().is_ident("cfg")
}

fn cfg_is_test(a: &Attribute) -> bool {
    matches!(&a.meta, Meta::List(l) if render_tokens(l.tokens.clone()) == "test")
}

/// `cfg(..)` annotations of an attribute list; `None` when the item is test-only.
fn cfgs_of(attrs: &[Attribute]) -> Option<Vec<String>> {
    let mut out = Vec::new();
    for a in attrs.iter().filter(|a| is_cfg(a)) {
        if cfg_is_test(a) {
            return None;
        }
        out.push(render(&a.meta));
    }
    Some(out)
}

/// The API-relevant attributes as `#[..]` text, in source order.
fn kept_attrs(attrs: &[Attribute]) -> Vec<String> {
    let mut out = Vec::new();
    for a in attrs {
        let name = attr_name(a);
        let hidden = name == "doc" && render(&a.meta).contains("hidden");
        if KEEP_ATTRS.contains(&name.as_str()) || hidden {
            out.push(format!("#[{}]", render(&a.meta)));
        }
    }
    out
}

fn with_attrs(text: String, attrs: &[Attribute]) -> String {
    let mut s = text;
    for a in kept_attrs(attrs) {
        s.push_str("  ");
        s.push_str(&a);
    }
    s
}

fn is_pub(v: &Visibility) -> bool {
    matches!(v, Visibility::Public(_))
}

// ------------------------------------------------------------------------------------------------ the module tree

#[derive(Debug)]
struct Def {
    name: String,
    public: bool,
    cfg: Vec<String>,
    /// `(suffix appended to the item path, text)`.
    lines: Vec<(String, String)>,
}

#[derive(Debug)]
struct UseLeaf {
    public: bool,
    cfg: Vec<String>,
    segs: Vec<String>,
    alias: Option<String>,
    glob: bool,
}

#[derive(Debug)]
struct ImplRec {
    cfg: Vec<String>,
    self_path: Option<Vec<String>>,
    /// `Some(header)` for a trait impl.
    trait_header: Option<String>,
    /// Inherent items: `(suffix, text, cfg)`.
    items: Vec<(String, String, Vec<String>)>,
}

#[derive(Debug, Default)]
struct ModNode {
    parent: Option<usize>,
    public: bool,
    cfg: Vec<String>,
    defs: Vec<Def>,
    uses: Vec<UseLeaf>,
    children: BTreeMap<String, usize>,
    impls: Vec<ImplRec>,
}

struct Tree {
    mods: Vec<ModNode>,
}

fn flatten_use(
    tree: &UseTree,
    prefix: &mut Vec<String>,
    out: &mut Vec<(Vec<String>, Option<String>, bool)>,
) {
    match tree {
        UseTree::Path(p) => {
            prefix.push(p.ident.unraw().to_string());
            flatten_use(&p.tree, prefix, out);
            prefix.pop();
        }
        UseTree::Name(n) => {
            let mut segs = prefix.clone();
            segs.push(n.ident.unraw().to_string());
            out.push((segs, None, false));
        }
        UseTree::Rename(r) => {
            let mut segs = prefix.clone();
            segs.push(r.ident.unraw().to_string());
            out.push((segs, Some(r.rename.unraw().to_string()), false));
        }
        UseTree::Glob(_) => out.push((prefix.clone(), None, true)),
        UseTree::Group(g) => {
            for t in &g.items {
                flatten_use(t, prefix, out);
            }
        }
    }
}

fn plain_attrs_stripped(attrs: &mut Vec<Attribute>) {
    attrs.clear();
}

fn fn_def(sig: &syn::Signature, attrs: &[Attribute]) -> String {
    let mut sig = sig.clone();
    for arg in &mut sig.inputs {
        match arg {
            syn::FnArg::Receiver(r) => r.attrs.retain(|a| !a.path().is_ident("doc")),
            syn::FnArg::Typed(t) => t.attrs.retain(|a| !a.path().is_ident("doc")),
        }
    }
    with_attrs(render(&sig), attrs)
}

fn struct_def(s: &syn::ItemStruct) -> Vec<(String, String)> {
    let mut head = s.clone();
    plain_attrs_stripped(&mut head.attrs);
    head.vis = Visibility::Inherited;
    head.fields = syn::Fields::Unit;
    let mut text = header(render(&head));
    let mut fields = Vec::new();
    let mut private = false;
    for (i, f) in s.fields.iter().enumerate() {
        if !is_pub(&f.vis) {
            private = true;
            continue;
        }
        let name = f
            .ident
            .as_ref()
            .map_or_else(|| i.to_string(), ToString::to_string);
        let Some(cfg) = cfgs_of(&f.attrs) else {
            continue;
        };
        let mut line = with_attrs(format!("field {}", render(&f.ty)), &f.attrs);
        for c in cfg {
            line.push_str(&format!("  [{c}]"));
        }
        fields.push((format!(".{name}"), line));
    }
    if private {
        text.push_str("  [private fields]");
    }
    let mut out = vec![(String::new(), with_attrs(text, &s.attrs))];
    out.extend(fields);
    out
}

fn enum_def(e: &syn::ItemEnum) -> Vec<(String, String)> {
    let mut head = e.clone();
    plain_attrs_stripped(&mut head.attrs);
    head.vis = Visibility::Inherited;
    head.variants.clear();
    let mut out = vec![(String::new(), with_attrs(header(render(&head)), &e.attrs))];
    for v in &e.variants {
        let mut v2 = v.clone();
        v2.attrs.clear();
        for f in &mut v2.fields {
            f.attrs.clear();
        }
        out.push((format!("::{}", v.ident), format!("variant {}", render(&v2))));
    }
    out
}

fn trait_def(t: &syn::ItemTrait) -> Vec<(String, String)> {
    let mut head = t.clone();
    plain_attrs_stripped(&mut head.attrs);
    head.vis = Visibility::Inherited;
    head.items.clear();
    let mut out = vec![(String::new(), with_attrs(header(render(&head)), &t.attrs))];
    for item in &t.items {
        match item {
            syn::TraitItem::Fn(f) => {
                let default = if f.default.is_some() {
                    "  [default body]"
                } else {
                    ""
                };
                out.push((
                    format!("::{}", f.sig.ident),
                    format!("{}{default}", fn_def(&f.sig, &f.attrs)),
                ));
            }
            syn::TraitItem::Type(ty) => {
                let mut ty = ty.clone();
                ty.attrs.clear();
                out.push((format!("::{}", ty.ident), header(render(&ty))));
            }
            syn::TraitItem::Const(c) => {
                let mut c = c.clone();
                c.attrs.clear();
                out.push((format!("::{}", c.ident), header(render(&c))));
            }
            _ => {}
        }
    }
    out
}

impl Tree {
    fn new_mod(&mut self, parent: Option<usize>, public: bool, cfg: Vec<String>) -> usize {
        self.mods.push(ModNode {
            parent,
            public,
            cfg,
            ..ModNode::default()
        });
        self.mods.len() - 1
    }

    fn add_def(
        &mut self,
        m: usize,
        name: String,
        public: bool,
        cfg: Vec<String>,
        lines: Vec<(String, String)>,
    ) {
        self.mods[m].defs.push(Def {
            name,
            public,
            cfg,
            lines,
        });
    }

    /// Parse `items` into module `m`; `dir` is where the file of a child `mod x;` is looked up.
    fn load_items(&mut self, m: usize, items: &[Item], dir: &Path) -> Result<(), String> {
        for item in items {
            self.load_item(m, item, dir)?;
        }
        Ok(())
    }

    fn load_item(&mut self, m: usize, item: &Item, dir: &Path) -> Result<(), String> {
        let attrs: &[Attribute] = match item {
            Item::Fn(i) => &i.attrs,
            Item::Struct(i) => &i.attrs,
            Item::Enum(i) => &i.attrs,
            Item::Trait(i) => &i.attrs,
            Item::Const(i) => &i.attrs,
            Item::Static(i) => &i.attrs,
            Item::Type(i) => &i.attrs,
            Item::Mod(i) => &i.attrs,
            Item::Use(i) => &i.attrs,
            Item::Impl(i) => &i.attrs,
            Item::Macro(i) => &i.attrs,
            _ => return Ok(()),
        };
        let Some(cfg) = cfgs_of(attrs) else {
            return Ok(());
        };
        match item {
            Item::Fn(f) => {
                let line = fn_def(&f.sig, &f.attrs);
                self.add_def(
                    m,
                    f.sig.ident.unraw().to_string(),
                    is_pub(&f.vis),
                    cfg,
                    vec![(String::new(), line)],
                );
            }
            Item::Struct(s) => self.add_def(
                m,
                s.ident.unraw().to_string(),
                is_pub(&s.vis),
                cfg,
                struct_def(s),
            ),
            Item::Enum(e) => self.add_def(
                m,
                e.ident.unraw().to_string(),
                is_pub(&e.vis),
                cfg,
                enum_def(e),
            ),
            Item::Trait(t) => self.add_def(
                m,
                t.ident.unraw().to_string(),
                is_pub(&t.vis),
                cfg,
                trait_def(t),
            ),
            Item::Const(c) => {
                let mut c2 = c.clone();
                c2.attrs.clear();
                c2.vis = Visibility::Inherited;
                let line = with_attrs(header(render(&c2)), &c.attrs);
                self.add_def(
                    m,
                    c.ident.unraw().to_string(),
                    is_pub(&c.vis),
                    cfg,
                    vec![(String::new(), line)],
                );
            }
            Item::Static(s) => {
                let mut s2 = s.clone();
                s2.attrs.clear();
                s2.vis = Visibility::Inherited;
                let line = with_attrs(header(render(&s2)), &s.attrs);
                self.add_def(
                    m,
                    s.ident.unraw().to_string(),
                    is_pub(&s.vis),
                    cfg,
                    vec![(String::new(), line)],
                );
            }
            Item::Type(t) => {
                let mut t2 = t.clone();
                t2.attrs.clear();
                t2.vis = Visibility::Inherited;
                let line = with_attrs(header(render(&t2)), &t.attrs);
                self.add_def(
                    m,
                    t.ident.unraw().to_string(),
                    is_pub(&t.vis),
                    cfg,
                    vec![(String::new(), line)],
                );
            }
            Item::Macro(mc) => {
                if let (Some(id), true) = (
                    &mc.ident,
                    mc.attrs.iter().any(|a| a.path().is_ident("macro_export")),
                ) {
                    self.add_def(
                        0,
                        id.to_string(),
                        true,
                        cfg,
                        vec![(String::new(), format!("macro {id}!"))],
                    );
                }
            }
            Item::Use(u) => {
                let mut leaves = Vec::new();
                flatten_use(&u.tree, &mut Vec::new(), &mut leaves);
                for (segs, alias, glob) in leaves {
                    self.mods[m].uses.push(UseLeaf {
                        public: is_pub(&u.vis),
                        cfg: cfg.clone(),
                        segs,
                        alias,
                        glob,
                    });
                }
            }
            Item::Mod(md) => {
                if md.attrs.iter().any(|a| a.path().is_ident("path")) {
                    return Err(format!(
                        "mod {}: #[path] modules are not supported",
                        md.ident
                    ));
                }
                let child = self.new_mod(Some(m), is_pub(&md.vis), cfg);
                self.mods[m]
                    .children
                    .insert(md.ident.unraw().to_string(), child);
                let name = md.ident.unraw().to_string();
                if let Some((_, inner)) = &md.content {
                    self.load_items(child, inner, &dir.join(&name))?;
                } else {
                    let flat = dir.join(format!("{name}.rs"));
                    let nested = dir.join(&name).join("mod.rs");
                    let (file, child_dir) = if flat.is_file() {
                        (flat, dir.join(&name))
                    } else if nested.is_file() {
                        (nested, dir.join(&name))
                    } else {
                        return Err(format!(
                            "mod {name}: neither {} nor {} exists",
                            flat.display(),
                            nested.display()
                        ));
                    };
                    self.load_file(child, &file, &child_dir)?;
                }
            }
            Item::Impl(im) => {
                let self_path = match &*im.self_ty {
                    Type::Path(p) if p.qself.is_none() => Some(
                        p.path
                            .segments
                            .iter()
                            .map(|s| s.ident.unraw().to_string())
                            .collect(),
                    ),
                    _ => None,
                };
                let mut rec = ImplRec {
                    cfg,
                    self_path,
                    trait_header: None,
                    items: Vec::new(),
                };
                if im.trait_.is_some() {
                    let mut head = im.clone();
                    head.attrs.clear();
                    head.items.clear();
                    rec.trait_header = Some(header(render(&head)));
                } else {
                    for it in &im.items {
                        match it {
                            ImplItem::Fn(f) if is_pub(&f.vis) => {
                                if let Some(c) = cfgs_of(&f.attrs) {
                                    rec.items.push((
                                        format!("::{}", f.sig.ident),
                                        fn_def(&f.sig, &f.attrs),
                                        c,
                                    ));
                                }
                            }
                            ImplItem::Const(c) if is_pub(&c.vis) => {
                                if let Some(cf) = cfgs_of(&c.attrs) {
                                    let mut c2 = c.clone();
                                    c2.attrs.clear();
                                    c2.vis = Visibility::Inherited;
                                    rec.items.push((
                                        format!("::{}", c.ident),
                                        header(render(&c2)),
                                        cf,
                                    ));
                                }
                            }
                            _ => {}
                        }
                    }
                }
                self.mods[m].impls.push(rec);
            }
            _ => {}
        }
        Ok(())
    }

    fn load_file(&mut self, m: usize, file: &Path, child_dir: &Path) -> Result<(), String> {
        let text = fs::read_to_string(file).map_err(|e| format!("{}: {e}", file.display()))?;
        let parsed = syn::parse_file(&text).map_err(|e| format!("{}: {e}", file.display()))?;
        self.load_items(m, &parsed.items, child_dir)
    }
}

// ------------------------------------------------------------------------------------------------ resolution

type DefId = (usize, usize);

#[derive(Debug)]
enum Resolved {
    Module(usize),
    Defs(Vec<DefId>),
    External,
    Unresolved,
}

impl Tree {
    fn resolve(&self, m: usize, segs: &[String]) -> Resolved {
        self.resolve_d(m, segs, 0)
    }

    fn resolve_d(&self, m: usize, segs: &[String], depth: usize) -> Resolved {
        if depth > 16 {
            return Resolved::Unresolved;
        }
        let (mut cur, mut rest) = (m, segs);
        let mut local_first = true;
        match segs.first().map(String::as_str) {
            Some("crate") => (cur, rest) = (0, &segs[1..]),
            Some("self") => rest = &segs[1..],
            Some("super") => {
                while let Some(("super", tail)) = rest.split_first().map(|(h, t)| (h.as_str(), t)) {
                    cur = self.mods[cur].parent.unwrap_or(0);
                    rest = tail;
                }
            }
            Some(first) => {
                let node = &self.mods[m];
                local_first = node.children.contains_key(first)
                    || node.defs.iter().any(|d| d.name == first)
                    || node.uses.iter().any(|u| {
                        !u.glob
                            && u.segs.len() > 1
                            && u.alias
                                .as_ref()
                                .or(u.segs.last())
                                .is_some_and(|n| n == first)
                    });
            }
            None => return Resolved::Unresolved,
        }
        if rest.is_empty() {
            return Resolved::Module(cur);
        }
        match self.resolve_from(cur, rest, depth) {
            Resolved::Unresolved if !local_first => Resolved::External,
            r => r,
        }
    }

    fn resolve_from(&self, cur: usize, rest: &[String], depth: usize) -> Resolved {
        if depth > 16 {
            return Resolved::Unresolved;
        }
        let name = &rest[0];
        let last = rest.len() == 1;
        let node = &self.mods[cur];
        if let Some(&c) = node.children.get(name) {
            return if last {
                Resolved::Module(c)
            } else {
                self.resolve_from(c, &rest[1..], depth + 1)
            };
        }
        let ids: Vec<DefId> = node
            .defs
            .iter()
            .enumerate()
            .filter(|(_, d)| &d.name == name)
            .map(|(i, _)| (cur, i))
            .collect();
        if !ids.is_empty() {
            return if last {
                Resolved::Defs(ids)
            } else {
                Resolved::Unresolved
            };
        }
        // `pub use some_crate;` names an external crate, not itself
        if let Some(u) = node.uses.iter().find(|u| {
            !u.glob && u.alias.as_ref().or(u.segs.last()) == Some(name) && u.segs.len() > 1
        }) {
            return match (self.resolve_d(cur, &u.segs, depth + 1), last) {
                (r, true) => r,
                (Resolved::Module(c), false) => self.resolve_from(c, &rest[1..], depth + 1),
                _ => Resolved::Unresolved,
            };
        }
        for u in node.uses.iter().filter(|u| u.glob) {
            if let Resolved::Module(t) = self.resolve_d(cur, &u.segs, depth + 1) {
                match self.resolve_from(t, rest, depth + 1) {
                    Resolved::Unresolved | Resolved::External => {}
                    found => return found,
                }
            }
        }
        Resolved::Unresolved
    }
}

// ------------------------------------------------------------------------------------------------ emission

struct Emitter<'a> {
    tree: &'a Tree,
    lines: Vec<String>,
    /// Where each definition is reachable, with the cfg annotations on the way.
    emitted: BTreeMap<DefId, Vec<(String, Vec<String>)>>,
    seen: BTreeSet<(usize, String)>,
}

fn join_path(path: &str, name: &str) -> String {
    if path.is_empty() {
        name.to_string()
    } else {
        format!("{path}::{name}")
    }
}

fn annotate(text: &str, cfgs: &[String]) -> String {
    let mut s = text.to_string();
    let mut seen = BTreeSet::new();
    for c in cfgs {
        if seen.insert(c) {
            s.push_str(&format!("  [{c}]"));
        }
    }
    s
}

impl Emitter<'_> {
    fn push(&mut self, path: &str, kind_text: &str, cfgs: &[String]) {
        self.lines
            .push(format!("{path}  {}", annotate(kind_text, cfgs)));
    }

    fn emit_def(&mut self, id: DefId, path: &str, cfgs: &[String]) {
        let def = &self.tree.mods[id.0].defs[id.1];
        let mut all = cfgs.to_vec();
        all.extend(def.cfg.iter().cloned());
        for (suffix, text) in &def.lines {
            let line = format!("{path}{suffix}  {}", annotate(text, &all));
            self.lines.push(line);
        }
        self.emitted
            .entry(id)
            .or_default()
            .push((path.to_string(), all));
    }

    fn emit_module(&mut self, m: usize, path: &str, cfgs: &[String]) {
        if !self.seen.insert((m, path.to_string())) {
            return;
        }
        let node = &self.tree.mods[m];
        for (i, def) in node.defs.iter().enumerate() {
            if def.public {
                self.emit_def((m, i), &join_path(path, &def.name), cfgs);
            }
        }
        for u in node.uses.iter().filter(|u| u.public) {
            let mut ucfg = cfgs.to_vec();
            ucfg.extend(u.cfg.iter().cloned());
            let shown = u.segs.join("::");
            let target = self.tree.resolve(m, &u.segs);
            if u.glob {
                match target {
                    Resolved::Module(t) => self.emit_module(t, path, &ucfg),
                    _ => self.push(&join_path(path, "*"), &format!("use {shown}::*"), &ucfg),
                }
                continue;
            }
            let name = u
                .alias
                .clone()
                .or_else(|| u.segs.last().cloned())
                .unwrap_or_default();
            let target_path = join_path(path, &name);
            let rename = u
                .alias
                .as_ref()
                .map_or(String::new(), |a| format!(" as {a}"));
            self.push(&target_path, &format!("use {shown}{rename}"), &ucfg);
            match target {
                Resolved::Module(t) => self.emit_module(t, &target_path, &ucfg),
                Resolved::Defs(ids) => {
                    for id in ids {
                        self.emit_def(id, &target_path, &ucfg);
                    }
                }
                Resolved::External => {}
                Resolved::Unresolved => eprintln!(
                    "public-api-snapshot: unresolved re-export `{shown}` in module {path:?}"
                ),
            }
        }
        let children: Vec<(String, usize)> =
            node.children.iter().map(|(n, &c)| (n.clone(), c)).collect();
        for (name, c) in children {
            let child = &self.tree.mods[c];
            if child.public {
                let mut ccfg = cfgs.to_vec();
                ccfg.extend(child.cfg.iter().cloned());
                let p = join_path(path, &name);
                self.push(&p, "mod", &ccfg);
                self.emit_module(c, &p, &ccfg);
            }
        }
    }

    fn emit_impls(&mut self) {
        for (m, node) in self.tree.mods.iter().enumerate() {
            for im in &node.impls {
                let Some(segs) = &im.self_path else { continue };
                let Resolved::Defs(ids) = self.tree.resolve(m, segs) else {
                    continue;
                };
                for id in ids {
                    let Some(paths) = self.emitted.get(&id).cloned() else {
                        continue;
                    };
                    for (path, cfgs) in paths {
                        let mut base = cfgs.clone();
                        base.extend(im.cfg.iter().cloned());
                        if let Some(h) = &im.trait_header {
                            self.lines.push(format!("{path}  {}", annotate(h, &base)));
                        }
                        for (suffix, text, c) in &im.items {
                            let mut all = base.clone();
                            all.extend(c.iter().cloned());
                            self.lines
                                .push(format!("{path}{suffix}  {}", annotate(text, &all)));
                        }
                    }
                }
            }
        }
    }
}

/// The snapshot of the crate whose `lib.rs` is in `root`.
fn snapshot(root: &Path) -> Result<String, String> {
    let mut tree = Tree { mods: Vec::new() };
    let r = tree.new_mod(None, true, Vec::new());
    tree.load_file(r, &root.join("lib.rs"), root)?;
    let mut em = Emitter {
        tree: &tree,
        lines: Vec::new(),
        emitted: BTreeMap::new(),
        seen: BTreeSet::new(),
    };
    em.emit_module(0, "", &[]);
    em.emit_impls();
    let mut lines = em.lines;
    lines.sort();
    lines.dedup();
    let mut out = String::from(
        "# Public API of dioxus-primitives, one line per item: path, kind and signature, annotations. Sorted.\n\
         # Generated by `scripts/check-public-api.sh --update` (public-api-snapshot over primitives/src); do not edit by hand.\n\
         # A diff here is a public-API change: review it as one.\n",
    );
    for l in lines {
        out.push_str(&l);
        out.push('\n');
    }
    Ok(out)
}

fn main() -> ExitCode {
    let mut root = PathBuf::from("primitives/src");
    let mut args = std::env::args().skip(1);
    while let Some(a) = args.next() {
        match (a.as_str(), args.next()) {
            ("--root", Some(v)) => root = PathBuf::from(v),
            _ => {
                eprintln!("usage: public-api-snapshot [--root <src dir>]");
                return ExitCode::from(2);
            }
        }
    }
    match snapshot(&root) {
        Ok(s) => {
            print!("{s}");
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("public-api-snapshot: {e}");
            ExitCode::from(2)
        }
    }
}

