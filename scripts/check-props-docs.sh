#!/usr/bin/env bash
# Every prop has a `///` doc comment, because every component page prints a Props reference table that
# `preview/build.rs` generates from the same scanner (`preview/props_scan.rs`). A field of a `#[derive(Props)]` struct
# must always be documented; an argument of a `#[component] fn` is checked against a shrink-only baseline
# (`scripts/check-props-docs.baseline.tsv`), so a new undocumented argument fails and so does a baseline entry that is
# now documented or gone. A `#[props(extends = ..)]` spread is not a prop; a component `docs.md` may not declare its
# own `## Props reference`.
#
# The docs site prints a props reference table on every component page, generated by `preview/build.rs`
# from the same scan (`preview/props_scan.rs`); an undocumented prop is a table row with an empty
# description. Two shapes of prop, both scanned in `primitives/src/**` and every
# `preview/src/components/*/component.rs`:
#   - a field of a `#[derive(Props)]` struct (pub or not: the builder setter is public either way): never
#     allowed without a doc comment;
#   - an argument of a `#[component] fn Name(a: A, ..)`: those that predate this gate are a shrink-only
#     baseline (`scripts/check-props-docs.baseline.tsv`, `path<TAB>Fn.arg`). A NEW undocumented argument
#     fails, and so does a baseline entry that is now documented or gone (delete the line).
# A `#[props(extends = ..)]` spread is not a prop (the table says "plus the global attributes") and is exempt.
# `--update-baseline` rewrites the baseline (only ever to shrink it: review the diff).
#
# The scanner is std-only, so a bare `rustc` builds it in about a second; no cargo lock needed.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

out="$(mktemp -d)"
trap 'rm -rf "$out"' EXIT
baseline=scripts/check-props-docs.baseline.tsv
rustc --edition 2021 -O -o "$out/props-scan" scripts/props-scan/main.rs 2>"$out/rustc.log" \
  || { cat "$out/rustc.log"; echo "check-props-docs: scanner failed to compile" >&2; exit 1; }

# Files split out of a `#[cfg(test)]` module (`tests.rs`, `*_tests.rs`) hold test components, not a public prop surface.
mapfile -t files < <({ find primitives/src -name '*.rs' ! -name tests.rs ! -name '*_tests.rs'; find preview/src/components -name component.rs; } | sort)
"$out/props-scan" "${files[@]}" >"$out/missing.tsv"

awk -F'\t' '$1=="FN"{print $2 "\t" $3}' "$out/missing.tsv" | LC_ALL=C sort -u >"$out/fn.tsv"
if [ "${1:-}" = "--update-baseline" ]; then
  cp "$out/fn.tsv" "$baseline"; echo "check-props-docs: baseline rewritten ($(wc -l <"$baseline") entries)"; exit 0
fi

rc=0
if awk -F'\t' '$1=="STRUCT"{printf "%s:%s: %s has no doc comment\n", $2, $4, $3; f=1} END{exit !f}' "$out/missing.tsv"; then
  rc=1
fi
LC_ALL=C sort -u "$baseline" >"$out/base.tsv"
new="$(LC_ALL=C comm -13 "$out/base.tsv" "$out/fn.tsv")"
stale="$(LC_ALL=C comm -23 "$out/base.tsv" "$out/fn.tsv")"
if [ -n "$new" ]; then
  echo "undocumented #[component] fn argument(s) not in the baseline:" >&2; echo "$new" | sed 's/^/  /' >&2; rc=1
fi
if [ -n "$stale" ]; then
  echo "stale baseline entries (documented or gone: delete from $baseline):" >&2; echo "$stale" | sed 's/^/  /' >&2; rc=1
fi
if [ "$rc" -eq 0 ]; then
  echo "check-props-docs: OK ($(wc -l <"$out/fn.tsv") baselined fn arguments left to document)"
else
  echo "check-props-docs: FAIL -- add a \`///\` comment above each prop (it becomes the Description column of the component's props table)" >&2
fi
exit "$rc"
