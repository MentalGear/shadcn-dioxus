#!/usr/bin/env bash
#
# build-kernel.sh   (backlog row 509)
#
# The ONE way to regenerate `primitives/src/kernel/` from `decision-kernel/`: the decision kernel as a wasm module, the
# same bytes as base64 text (what the Rust transport evaluates into the page), and `kernel.manifest`.
#
# Usage: CARGO_TARGET_DIR=<absolute dir> scripts/build-kernel.sh [--out DIR] [--root DIR]
#   Builds `decision-kernel` for wasm32-unknown-unknown under its own `[profile.kernel]` (the root `Cargo.toml`: it
#   inherits nothing from `[profile.release]`, `panic = "abort"`, opt-level z, fat LTO, stripped) with no RUSTFLAGS
#   from the environment, on the toolchain `rust-toolchain.toml` pins, and writes into `primitives/src/kernel/` (or
#   `--out`):
#     decision-kernel.wasm   the module
#     decision-kernel.b64    the module as one line of base64
#     kernel.manifest        `rustc -Vv` without its `host:` line, the target, the text and hash of the profile, the
#                            sha256 and git blob id of every input file (the crate's sources, `rust-toolchain.toml`),
#                            and the sha256 of the module
#   `--root DIR` builds a workspace laid out by scripts/merge-driver-kernel.py (the merged inputs of two lanes) instead of
#   this repository; it is the merge driver's call and has no `--locked` (that workspace has only this crate).
#   Run it inside the build queue (scripts/lane-lock.sh) like any cargo command. The module embeds no checkout path
#   (std's panic locations name `/rustc/<commit>/...`), so its bytes depend on the inputs the manifest lists and on
#   the toolchain only. `scripts/check-decision-kernel.sh` holds the committed files to that.
#   `dioxus-primitives` has no build script: the committed files are what its transport includes.

set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
root="$here"
out=""
while [ $# -gt 0 ]; do
  case "$1" in
    --out) out="${2:?}"; shift 2 ;;
    --root) root="${2:?}"; shift 2 ;;
    *) echo "usage: $0 [--out DIR] [--root DIR]" >&2; exit 2 ;;
  esac
done
case "${CARGO_TARGET_DIR:-}" in /*) ;; *) echo "build-kernel: CARGO_TARGET_DIR must be an absolute path" >&2; exit 2 ;; esac
cd "$root"
[ -n "$out" ] || out="$root/primitives/src/kernel"
locked=(--locked)
[ "$root" = "$here" ] || locked=()

env -u RUSTFLAGS -u CARGO_ENCODED_RUSTFLAGS -u RUSTC_WRAPPER CARGO_INCREMENTAL=0 \
  cargo build "${locked[@]}" -p decision-kernel --profile kernel --target wasm32-unknown-unknown >&2
built="$CARGO_TARGET_DIR/wasm32-unknown-unknown/kernel/decision_kernel.wasm"
[ -f "$built" ] || { echo "build-kernel: $built was not produced" >&2; exit 1; }

mkdir -p "$out"
cp "$built" "$out/decision-kernel.wasm"
base64 -w0 "$out/decision-kernel.wasm" > "$out/decision-kernel.b64"

# The `[profile.kernel]` table of the root Cargo.toml, verbatim (the table, not the file: an unrelated crate added to the
# workspace must not stale the module).
profile="$(awk '/^\[profile\.kernel\]/{on=1; print; next} /^\[/{on=0} on && NF{print}' Cargo.toml)"
[ -n "$profile" ] || { echo "build-kernel: Cargo.toml has no [profile.kernel]" >&2; exit 1; }

{
  echo "# Generated by scripts/build-kernel.sh -- do not edit by hand."
  echo "# The inputs of decision-kernel.wasm (toolchain, profile, sources) and the hash of the module."
  rustc -Vv | grep -v '^host:' | sed 's/^/rustc: /'
  echo "target: wasm32-unknown-unknown"
  printf 'profile-sha256 %s\n' "$(printf '%s\n' "$profile" | sha256sum | cut -d' ' -f1)"
  printf '%s\n' "$profile" | sed 's/^/profile> /'
  { find decision-kernel/Cargo.toml decision-kernel/src -type f; echo rust-toolchain.toml; } | LC_ALL=C sort | while read -r f; do
    printf 'src %s %s %s\n' "$(sha256sum "$f" | cut -d' ' -f1)" "$(git hash-object --no-filters "$f")" "$f"
  done
  printf 'wasm %s  decision-kernel.wasm (%s bytes)\n' "$(sha256sum "$out/decision-kernel.wasm" | cut -d' ' -f1)" "$(wc -c < "$out/decision-kernel.wasm" | tr -d ' ')"
} > "$out/kernel.manifest"
echo "build-kernel: wrote $out/decision-kernel.wasm ($(wc -c < "$out/decision-kernel.wasm") bytes, gzip -9 $(gzip -9c "$out/decision-kernel.wasm" | wc -c))" >&2
