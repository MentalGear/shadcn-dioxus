#!/usr/bin/env bash
#
# build-kernel.sh
#
# The ONE way to regenerate `primitives/src/kernel/` from `decision-kernel/`: the decision kernel as a wasm module,
# the same bytes as base64 text (what the Rust transport evaluates into the page), and a manifest.
#
# Usage: CARGO_TARGET_DIR=<absolute dir> scripts/build-kernel.sh [--out <dir>]
#   Builds `decision-kernel` for wasm32-unknown-unknown in the workspace's release profile (opt-level z, fat LTO,
#   stripped), with no RUSTFLAGS from the environment, and writes into `primitives/src/kernel/` (or `--out`):
#     decision-kernel.wasm   the module
#     decision-kernel.b64    the module as one line of base64
#     kernel.manifest        the toolchain (`rustc -Vv`) and the sha256 of every source file and of the module
#   Run it inside the build queue (scripts/lane-lock.sh) like any cargo command. The module embeds no checkout path
#   (std's panic locations name `/rustc/<commit>/...`), so the bytes depend on the sources and the toolchain only.

set -euo pipefail
cd "$(dirname "$0")/.."

out=primitives/src/kernel
if [ "${1:-}" = "--out" ]; then out="${2:?}"; shift 2; fi
case "${CARGO_TARGET_DIR:-}" in /*) ;; *) echo "build-kernel: CARGO_TARGET_DIR must be an absolute path" >&2; exit 2 ;; esac

env -u RUSTFLAGS -u CARGO_ENCODED_RUSTFLAGS CARGO_INCREMENTAL=0 \
  cargo build --locked -p decision-kernel --release --target wasm32-unknown-unknown >&2
built="$CARGO_TARGET_DIR/wasm32-unknown-unknown/release/decision_kernel.wasm"
[ -f "$built" ] || { echo "build-kernel: $built was not produced" >&2; exit 1; }

mkdir -p "$out"
cp "$built" "$out/decision-kernel.wasm"
base64 -w0 "$out/decision-kernel.wasm" > "$out/decision-kernel.b64"
{
  echo "# Generated by scripts/build-kernel.sh -- do not edit by hand."
  echo "# The toolchain that built decision-kernel.wasm, the sha256 of every source file and of the module."
  rustc -Vv | sed 's/^/rustc: /'
  echo "target: wasm32-unknown-unknown"
  echo "profile: release (opt-level z, fat LTO, strip), no RUSTFLAGS"
  find decision-kernel/Cargo.toml decision-kernel/src -type f | LC_ALL=C sort | while read -r f; do
    printf 'src %s  %s\n' "$(sha256sum "$f" | cut -d' ' -f1)" "$f"
  done
  printf 'wasm %s  decision-kernel.wasm (%s bytes)\n' "$(sha256sum "$out/decision-kernel.wasm" | cut -d' ' -f1)" "$(wc -c < "$out/decision-kernel.wasm" | tr -d ' ')"
} > "$out/kernel.manifest"
echo "build-kernel: wrote $out/decision-kernel.wasm ($(wc -c < "$out/decision-kernel.wasm") bytes)" >&2
