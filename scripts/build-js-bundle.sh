#!/usr/bin/env bash
#
# build-js-bundle.sh
#
# The ONE way to regenerate `primitives/src/js/*.js` from `primitives/src/ts/*.ts`.
#
# The bundle used to be rebuilt by `primitives/build.rs` (the `lazy-js-bundle` crate): a build script that ran,
# and could shell out to `bun`, in EVERY consumer's build of dioxus-primitives, and whose staleness check hashed
# with `std::hash::DefaultHasher` (std documents that hasher as not stable across Rust releases). The build script
# is gone (dev-docs/backlog.md row 217); the generated `.js` is committed, and `scripts/check-js-bundle.sh` proves
# it still belongs to its `.ts` source.
#
# Usage: scripts/build-js-bundle.sh
#   Rebuilds every primitives/src/ts/<name>.ts into primitives/src/js/<name>.js with
#   `bun build --minify-whitespace --minify-syntax` (the flags lazy-js-bundle used) and rewrites
#   primitives/src/js/bundle.manifest (the bun version plus the sha256 of each .ts and .js). Commit all three.
#   Needs `bun` (https://bun.sh); the gate itself does not.

set -euo pipefail
cd "$(dirname "$0")/.."

command -v bun >/dev/null || { echo "build-js-bundle: bun is not installed (https://bun.sh)" >&2; exit 2; }

ts_dir=primitives/src/ts
js_dir=primitives/src/js
manifest=$js_dir/bundle.manifest

shopt -s nullglob
sources=("$ts_dir"/*.ts)
[ "${#sources[@]}" -gt 0 ] || { echo "build-js-bundle: no .ts files in $ts_dir" >&2; exit 2; }

mkdir -p "$js_dir"
{
  echo "# Generated by scripts/build-js-bundle.sh -- do not edit by hand."
  echo "# Verified by scripts/check-js-bundle.sh (run-gates.sh): the sha256 of every src/ts/*.ts and src/js/*.js,"
  echo "# and, when the installed bun has the version below, a byte-identical rebuild."
  echo "bun $(bun --version)"
} > "$manifest.tmp"

for ts in "${sources[@]}"; do
  name="$(basename "$ts" .ts)"
  js="$js_dir/$name.js"
  bun build "$ts" --outfile "$js" --minify-whitespace --minify-syntax >/dev/null
  printf 'ts %s  %s\n' "$(sha256sum "$ts" | cut -d' ' -f1)" "$name.ts" >> "$manifest.tmp"
  printf 'js %s  %s\n' "$(sha256sum "$js" | cut -d' ' -f1)" "$name.js" >> "$manifest.tmp"
  echo "build-js-bundle: $ts -> $js"
done
mv "$manifest.tmp" "$manifest"
echo "build-js-bundle: wrote $manifest"
