#!/usr/bin/env python3
"""Git merge driver for the generated backlog indexes dev-docs/backlog.md and dev-docs/backlog-done.md (backlog row 400).

    python3 -I scripts/merge-driver-backlog-index.py %O %A %B [%P]     merge into %A; exit 0 (clean) or 1 (conflict)
    python3 -I scripts/merge-driver-backlog-index.py --self-test

The index tables are generated by scripts/backlog-index.sh from the row files, one table line per row, so two lanes
that each add a row both change the same region of the file and git always conflicts. Git runs a merge driver BEFORE
the working tree holds the merge (no MERGE_HEAD yet, the other side's row files are not checked out), so the driver
cannot regenerate the index from the row files. It does what regeneration would do from the three index versions
alone:
  - the text outside the generated block (the hand-written header, anything after END) is merged with
    `git merge-file`, a real 3-way text merge, so a header conflict stays a conflict;
  - the generated block is merged BY ROW: per id, the side that changed the row's line relative to the base wins
    (ours when both changed it differently), a row added or removed by one side stays so; the row lines are then
    sorted by id and the `## Open rows (N)` / `## Done rows (N)` count is recomputed, exactly as render_open and
    render_done in scripts/backlog-index.py write them.
The row files themselves are separate paths that git merges (or conflicts) on its own; scripts/check-backlog-index.sh
(a gate) still compares the merged index with the row files, so a merge whose index and rows disagree is red there.
scripts/check-merge-drivers.sh runs the self-test and a real two-branch merge. Registered by
scripts/setup-merge-drivers.sh.
"""
import os
import re
import subprocess
import sys
import tempfile

BEGIN = "<!-- BEGIN GENERATED: scripts/backlog-index.sh rewrites everything up to END; edit the row files, not this block -->"
END = "<!-- END GENERATED -->"
PLACEHOLDER = "@@GENERATED-BLOCK@@\n"
ROW_RE = re.compile(r"^\| \[(\d+)\]\(")
COUNT_RE = re.compile(r"^(## (?:Open|Done) rows \()\d+(\)\s*)$")


def split(text):
    """-> (outside text with the block replaced by PLACEHOLDER, block lines) or None when the markers are missing."""
    a, b = text.find(BEGIN), text.find(END)
    if a < 0 or b < a:
        return None
    b += len(END)
    return text[:a] + PLACEHOLDER + text[b:], text[a:b].split("\n")


def rows_of(block):
    return {int(m.group(1)): line for line in block if (m := ROW_RE.match(line))}


def merge_blocks(base, ours, theirs):
    b, o, t = rows_of(base), rows_of(ours), rows_of(theirs)
    merged = {}
    for k in set(b) | set(o) | set(t):
        bv, ov, tv = b.get(k), o.get(k), t.get(k)
        v = tv if ov == bv else ov  # ours changed it (or both did): ours; only theirs changed it: theirs
        if v is not None:
            merged[k] = v
    # the non-row lines (markers, heading, table header) come from ours, the count is recomputed
    out, placed = [], False
    for line in ours:
        if ROW_RE.match(line):
            if not placed:
                out += [merged[k] for k in sorted(merged)]
                placed = True
            continue
        m = COUNT_RE.match(line)
        out.append(f"{m.group(1)}{len(merged)}{m.group(2)}" if m else line)
    if not placed:  # ours has no rows: the rows go after the table header lines, before the blank line preceding END
        i = len(out) - 2 if len(out) >= 2 and out[-2] == "" else len(out) - 1
        out[i:i] = [merged[k] for k in sorted(merged)]
    return "\n".join(out)


def merge_file(ours, base, theirs):
    """git merge-file on three strings -> (text, conflicts)"""
    with tempfile.TemporaryDirectory() as d:
        paths = []
        for n, s in (("ours", ours), ("base", base), ("theirs", theirs)):
            p = os.path.join(d, n)
            with open(p, "w", encoding="utf-8", newline="") as f:
                f.write(s)
            paths.append(p)
        r = subprocess.run(["git", "merge-file", "-p", *paths], capture_output=True, text=True)
        if r.returncode < 0 or r.returncode > 127:
            raise RuntimeError(r.stderr.strip() or "git merge-file failed")
        return r.stdout, r.returncode


def merge(base_text, ours_text, theirs_text):
    """-> (merged text, conflicted: bool); None for the text when a version has no generated block."""
    parts = [split(x) for x in (base_text, ours_text, theirs_text)]
    if any(p is None for p in parts):
        return None, True
    (b_out, b_blk), (o_out, o_blk), (t_out, t_blk) = parts
    outside, conflicts = merge_file(o_out, b_out, t_out)
    return outside.replace(PLACEHOLDER, merge_blocks(b_blk, o_blk, t_blk), 1), conflicts > 0


def read(path):
    with open(path, encoding="utf-8", newline="") as f:
        return f.read()


def run(pb, po, pt):
    base = read(pb)
    if base.strip() == "":  # add/add: no base, the empty block merges as "both sides added every row"
        base = BEGIN + "\n\n" + END
    text, conflicted = merge(base, read(po), read(pt))
    if text is None:
        print("merge-driver-backlog-index: an index version has no BEGIN/END GENERATED markers; merge it by hand", file=sys.stderr)
        return 1
    with open(po, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    if conflicted:
        print("merge-driver-backlog-index: the hand-written text outside the generated block conflicts; resolve the markers, then run scripts/backlog-index.sh", file=sys.stderr)
    return 1 if conflicted else 0


def self_test():
    def index(rows, header="# Backlog\n\nintro\n", footer="\n"):
        lines = [BEGIN, "", f"## Open rows ({len(rows)})", "", "| # | Item | Status / trigger | Size | Area |", "|---|---|---|---|---|"]
        lines += [f"| [{i}](backlog/{i:03d}-x.md) | {t} | s | S | a |" for i, t in sorted(rows.items())]
        lines += ["", END]
        return header + "\n".join(lines) + footer

    base = index({4: "four", 23: "tw3", 152: "old"})

    def check(cond, what):
        if not cond:
            raise SystemExit(f"merge-driver-backlog-index: self-test FAILED: {what}")

    # 1. each side adds a row: both rows land, in id order, with the right count; identical to a regenerated index
    text, conflict = merge(base, index({4: "four", 23: "tw3", 152: "old", 400: "ours"}), index({4: "four", 23: "tw3", 152: "old", 401: "theirs"}))
    check(not conflict and text == index({4: "four", 23: "tw3", 152: "old", 400: "ours", 401: "theirs"}), "two added rows")
    # 2. one side edits a row, the other adds one; a row removed by one side stays removed
    text, conflict = merge(base, index({4: "FOUR", 23: "tw3", 152: "old"}), index({23: "tw3", 152: "old", 9: "nine"}))
    check(not conflict and text == index({4: "FOUR", 9: "nine", 23: "tw3", 152: "old"}), f"edit plus add, got:\n{text}")
    text, conflict = merge(base, index({4: "four", 23: "tw3"}), index({4: "four", 23: "tw3", 152: "old"}))
    check(not conflict and text == index({4: "four", 23: "tw3"}), "a removal by ours stands")
    # 3. both sides edit the same row differently: ours wins (the row file itself conflicts in git if it matters)
    text, conflict = merge(base, index({4: "A", 23: "tw3", 152: "old"}), index({4: "B", 23: "tw3", 152: "old"}))
    check(not conflict and text == index({4: "A", 23: "tw3", 152: "old"}), "same row edited twice keeps ours")
    # 4. hand-written text: edits on both sides in different places merge; in the same place they conflict
    text, conflict = merge(base, index({4: "four", 23: "tw3", 152: "old", 400: "o"}, header="# Backlog\n\nintro ours\n"),
                           index({4: "four", 23: "tw3", 152: "old", 401: "t"}, footer="\nfooter theirs\n"))
    check(not conflict and "intro ours" in text and "footer theirs" in text and "| [400]" in text and "| [401]" in text, "header and footer edits")
    text, conflict = merge(base, index({4: "four", 23: "tw3", 152: "old"}, header="# Backlog\n\nours\n"), index({4: "four", 23: "tw3", 152: "old"}, header="# Backlog\n\ntheirs\n"))
    check(conflict and "<<<<<<<" in text, "a header edited on both sides conflicts")
    # 5. add/add with an empty base and a missing marker
    with tempfile.TemporaryDirectory() as d:
        pb, po, pt = (os.path.join(d, n) for n in ("b", "o", "t"))
        open(pb, "w").close()
        open(po, "w").write(index({1: "a"}))
        open(pt, "w").write(index({2: "b"}))
        check(run(pb, po, pt) == 0 and open(po).read() == index({1: "a", 2: "b"}), "add/add with an empty base")
        open(pt, "w").write("no markers\n")
        keep = open(po).read()
        check(run(pb, po, pt) == 1 and open(po).read() == keep, "a version without markers is a conflict that leaves ours")
    print("merge-driver-backlog-index: self-test OK -- 7 cases")


if __name__ == "__main__":
    a = sys.argv[1:]
    if a[:1] == ["--self-test"]:
        self_test()
    elif len(a) >= 3:
        sys.exit(run(a[0], a[1], a[2]))
    else:
        print(__doc__)
        sys.exit(2)
