#!/usr/bin/env python3
"""Generate dev-docs/gates.md from the gate list of scripts/run-gates.sh and the headers of scripts/check-*.sh.

    scripts/gates-doc.py --write    regenerate dev-docs/gates.md
    scripts/gates-doc.py --check    exit 1 when dev-docs/gates.md differs from the generated text, or when a gate
                                    has no usable description (scripts/check-gates-doc.sh runs this)
    scripts/gates-doc.py --self-test

One source per gate, so the page cannot drift and a new gate never needs a prose edit anywhere else:
  - a `scripts/check-NAME.sh` gate is described by the FIRST PARAGRAPH of its header comment (the comment lines
    before the first blank `#` line, after an optional `check-NAME.sh -- title` line and a `Gate:` prefix);
  - any other gate (fmt, clippy, test, ...) is described by the `#` comment lines directly above its entry in the
    gate list of run-gates.sh;
  - the group a gate sits under is the nearest `# group: <title>` line above its entry in that list;
  - a cargo gate (the CARGO_GATES regex of run-gates.sh) is marked as such.
The output is a pure function of those inputs: no dates, no counts that are not derived, stable order.

A description is too thin below MIN_CHARS (a wrapper note, a bare title), unfinished when it ends with a colon, and
too long above MAX_CHARS (the rest of the header is the place for detail, gates.md links to it).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUN_GATES = os.path.join(ROOT, "scripts", "run-gates.sh")
OUT = os.path.join(ROOT, "dev-docs", "gates.md")
MIN_CHARS = 100
MAX_CHARS = 1100

INTRO = """\
# Gates

Generated by `scripts/gates-doc.py` from the gate list in `scripts/run-gates.sh` and the headers of
`scripts/check-*.sh`; `scripts/check-gates-doc.sh` fails when this page differs from the generated text. **Do not edit
it by hand.** Each gate's header is the full account (allowlists, escape-hatch markers, self-tests); this page prints
its first paragraph and links the script.

## Running them

`CARGO_TARGET_DIR=<absolute isolated dir> scripts/run-gates.sh` runs every gate, in the order below, with timings.
Green is **`ALL GREEN` with exit 0** and quotes only the tree it ran on (the summary prints HEAD plus a diff hash).
Exit 1 is a red gate, exit 2 bad usage or environment, exit 3 a green but partial run (`--only REGEX`,
`--skip REGEX`, `--fast`, `--stop-on-fail`): none of them is the full gate. `--list` prints the names.

- **Lanes** run the fast gates, everything except the cargo ones (every static check, `fmt` and `stylelint`, in
  seconds, no build lock): `scripts/run-gates.sh --fast` (exit 3 is expected). The main loop runs the one full run per merge batch
  ([`lane-rules.md`](./lane-rules.md), "Gate procedure").
- **Cargo-gate reuse (row 320).** A cargo gate stores its PASS under a key made of `scripts/cargo-inputs-hash.sh`
  (every file the cargo gates can read: the cargo crates by content, asset-only `css`, `svg`, images and fonts by path,
  `Cargo.toml` and `Cargo.lock`, every `include_str!`/`include_bytes!` target, the toolchain, `RUSTFLAGS` and the gate
  command lines). A later run with a byte-identical key prints `reused from tree <sha>` and the summary names every
  reused gate and the tree it really ran on. Only a PASS is stored, `fmt` is never reused, `--no-reuse` (or
  `GATE_REUSE=0`) forces the real run. A CSS-only tree went from 1,209 s to 127 s.
- **A new gate**: write the script's header (its first paragraph is the summary below), add one line to the gate list
  in `scripts/run-gates.sh` under its group, run `scripts/gates-doc.py --write`. A `scripts/check-*.sh` that is not in
  the list fails the run. Nothing else names a gate, so no other doc needs an edit.
- Other checks outside the gate run: `scripts/registry-install-smoke.sh` (the install check, run when a
  `component.json` or a component's `component.rs`/`mod.rs`/`style.css` changes), the Playwright suite
  ([`lane-rules.md`](./lane-rules.md), "Running the suite"), `scripts/check-comment-refs.sh`
  and `scripts/check-history-comments.sh` ([`history-in-comments.md`](./history-in-comments.md)).
"""


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def header_lines(text):
    """The leading comment block of a script, `# ` stripped, shebang skipped."""
    out = []
    for i, line in enumerate(text.split("\n")):
        if i == 0 and line.startswith("#!"):
            continue
        if line.startswith("#"):
            out.append(re.sub(r"^# ?", "", line))
        else:
            break
    return out


def first_paragraph(lines, name):
    """The summary paragraph of a check script's header, as one line."""
    lines = list(lines)
    while lines and not lines[0].strip():
        lines.pop(0)
    # an optional title line: `check-NAME.sh`, `check-NAME.sh -- title`, `check-NAME.sh  (backlog row N)`
    if lines and re.match(r"^" + re.escape(name) + r"(\.sh)?(\s|$)", lines[0].strip()):
        title = lines.pop(0).strip()
        m = re.match(r"^" + re.escape(name) + r"(?:\.sh)?\s*--\s*(.+)$", title)
        if m and lines and lines[0].strip():
            # `check-x.sh -- text` followed by more text without a blank line: the text starts the paragraph
            lines.insert(0, m.group(1))
    while lines and not lines[0].strip():
        lines.pop(0)
    para = []
    for line in lines:
        if not line.strip():
            break
        para.append(line.strip())
    text = re.sub(r"\s+", " ", " ".join(para)).strip()
    text = re.sub(r"^Gate(?: \([^)]*\))?:\s*", "", text)
    return text


def problems(name, text):
    out = []
    if len(text) < MIN_CHARS:
        out.append(f"{name}: description too thin ({len(text)} chars, need {MIN_CHARS}+): {text!r}")
    if len(text) > MAX_CHARS:
        out.append(f"{name}: description too long ({len(text)} chars, at most {MAX_CHARS}); keep detail in the later paragraphs")
    if text.rstrip().endswith(":"):
        out.append(f"{name}: the first paragraph ends with a colon, so it introduces something it does not say")
    return out


def parse_gate_list(src):
    """[(group, name, cmd, [comment lines above])] in list order, plus the CARGO_GATES regex."""
    m = re.search(r"^gates=\(\n(.*?)\n\)\n", src, re.S | re.M)
    if not m:
        raise SystemExit("gates-doc: no `gates=(` list in scripts/run-gates.sh")
    group = None
    pending = []
    gates = []
    for line in m.group(1).split("\n"):
        s = line.strip()
        if not s:
            continue
        if s.startswith("#"):
            g = re.match(r"^#\s*group:\s*(.+)$", s)
            if g:
                group = g.group(1).strip()
                pending = []
            else:
                pending.append(re.sub(r"^#\s?", "", s))
            continue
        e = re.match(r'^"([^|]+)\|(.*)"$', s)
        if not e:
            raise SystemExit(f"gates-doc: cannot parse gate list line: {s}")
        if group is None:
            raise SystemExit(f"gates-doc: gate {e.group(1)} has no `# group:` line above it")
        gates.append((group, e.group(1), e.group(2), pending))
        pending = []
    cg = re.search(r"^CARGO_GATES='([^']+)'", src, re.M)
    if not cg:
        raise SystemExit("gates-doc: CARGO_GATES not found in scripts/run-gates.sh")
    return gates, re.compile(cg.group(1))


def render(root=ROOT):
    src = read(os.path.join(root, "scripts", "run-gates.sh"))
    gates, cargo_re = parse_gate_list(src)
    errors = []
    groups = []  # ordered unique
    for g in gates:
        if g[0] not in groups:
            groups.append(g[0])
    out = [INTRO.rstrip("\n"), ""]
    for group in groups:
        out.append(f"## {group}")
        out.append("")
        for g, name, cmd, above in gates:
            if g != group:
                continue
            m = re.match(r"^(scripts/check-[a-z0-9-]+\.sh)$", cmd)
            if m:
                if above:
                    errors.append(f"{name}: comment lines above a check script's entry are ignored; its header is the description")
                path = os.path.join(root, m.group(1))
                if not os.path.exists(path):
                    errors.append(f"{name}: {m.group(1)} does not exist")
                    continue
                text = first_paragraph(header_lines(read(path)), os.path.basename(path)[:-3])
                link = f" ([`{m.group(1)}`](../{m.group(1)}))"
            else:
                if not above:
                    errors.append(f"{name}: a gate that is not a check script needs `#` comment lines above its entry in scripts/run-gates.sh")
                    continue
                text = re.sub(r"\s+", " ", " ".join(above)).strip()
                link = ""
            errors.extend(problems(name, text))
            mark = " *(cargo gate)*" if cargo_re.search(name) else ""
            out.append(f"**`{name}`**{mark}{link}: {text}")
            out.append("")
    return "\n".join(out).rstrip("\n") + "\n", errors


def self_test():
    ok = True

    def expect(cond, what):
        nonlocal ok
        print(("  ok   " if cond else "  FAIL ") + what)
        ok = ok and cond

    h = header_lines("#!/usr/bin/env bash\n#\n# check-x.sh -- one title\n#\n# Para one line one\n# line two.\n#\n# Second.\nset -e\n")
    expect(first_paragraph(h, "check-x") == "Para one line one line two.", "title line and blank lines are skipped, the paragraph is joined")
    h = header_lines("# Gate (backlog row 9): every prop has a doc.\n#\n# More.\n")
    expect(first_paragraph(h, "check-x") == "every prop has a doc.", "a `Gate (...):` prefix is dropped")
    h = header_lines("# check-x.sh  (backlog row 295)\n#\n# Real text here.\n")
    expect(first_paragraph(h, "check-x") == "Real text here.", "a title with a row note is dropped")
    expect(problems("g", "Wrapper: the gate lives elsewhere."), "a thin description is reported")
    expect(problems("g", "x" * 100 + ":"), "a description ending in a colon is reported")
    expect(problems("g", "x" * (MAX_CHARS + 1)), "an over-long description is reported")
    expect(not problems("g", "x" * 150), "a normal description passes")
    try:
        parse_gate_list('gates=(\n  "a|scripts/check-a.sh"\n)\nCARGO_GATES=\'^x$\'\n')
        expect(False, "a gate before any group line is refused")
    except SystemExit:
        expect(True, "a gate before any group line is refused")
    out, errs = render()
    expect(not errs, "the real tree has a usable description for every gate")
    expect(out == render()[0], "the output is deterministic")
    return 0 if ok else 1


def main(argv):
    if "--self-test" in argv:
        return self_test()
    text, errors = render()
    if "--write" in argv:
        for e in errors:
            print("gates-doc: " + e, file=sys.stderr)
        if errors:
            return 1
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"gates-doc: wrote {os.path.relpath(OUT, ROOT)} ({len(text)} bytes)")
        return 0
    if "--check" in argv:
        for e in errors:
            print("gates-doc: " + e, file=sys.stderr)
        if errors:
            return 1
        have = read(OUT) if os.path.exists(OUT) else ""
        if have != text:
            print("gates-doc: dev-docs/gates.md is stale; run scripts/gates-doc.py --write and commit it", file=sys.stderr)
            return 1
        print(f"gates-doc: dev-docs/gates.md is current ({len(text)} bytes)")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
